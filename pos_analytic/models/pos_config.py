from odoo import fields, models


class PosConfig(models.Model):
    _inherit = 'pos.config'

    analytic_account_id = fields.Many2one(
        'account.analytic.account',
        string='Analytic Account',
        check_company=True,
        help="Analytic account applied to every accounting entry generated by this "
             "point of sale (session closing entry, payments, cash moves, invoices, "
             "stock valuation).",
    )
    analytic_all_lines = fields.Boolean(
        string='Apply to balance sheet lines',
        help="By default only profit & loss journal items (income, expense, cost of "
             "goods sold) get the analytic account. Enable this to also tag "
             "receivable, cash, bank and stock valuation lines.",
    )

    def _get_pos_analytic_context(self):
        """Context keys that make ``account.move.line`` apply this POS's analytic account."""
        config = self[:1]
        if not config.analytic_account_id:
            return {}
        return {
            'pos_analytic_account_id': config.analytic_account_id.id,
            'pos_analytic_all_lines': config.analytic_all_lines,
        }
